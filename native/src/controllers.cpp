// Root: u8 flags, u8 headset battery, u16 controller mask, f32 ?, f32 ipd @8; ptr 0 entry list.
// Entry (8 words): u8 index, u8 battery, u8 type, u32 buttons @4, u32 touches @8, f32 trigger
// @0x0c, grip @0x10, stick x/y @0x14.
constexpr size_t kEntryBytes = 0x1C;

float f32(std::span<const uint8_t> s, size_t at) {
    uint32_t u = rd32(&s[at]);
    float f;
    std::memcpy(&f, &u, 4);
    return f;
}

