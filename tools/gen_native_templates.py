"""Generate native/src/templates_data.cpp: the recorded messages the native host builds from.

- PC control templates (first per (type, version)) from tests/fixtures/handshake/control.json,
  as Meta's raw Cap'n Proto bytes; the host decodes them, patches the session id, re-encodes.
- Post-handshake stream setup messages and the per-topic EncodedSlice segment table + header
  from host/replay/meta-idr.json.

The C++ test `templates_match_fixtures` checks the output against the fixtures, so rerun this
after re-extracting them.

Usage: py tools/gen_native_templates.py
"""
import json
import os
import struct

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "native", "src", "templates_data.cpp")


def c_bytes(data, indent="    "):
    lines = []
    for i in range(0, len(data), 16):
        lines.append(indent + " ".join(f"0x{b:02x}," for b in data[i:i + 16]))
    return "\n".join(lines) if lines else indent


def main():
    with open(os.path.join(ROOT, "tests", "fixtures", "handshake", "control.json"), encoding="utf-8") as f:
        control = json.load(f)
    with open(os.path.join(ROOT, "host", "replay", "meta-idr.json"), encoding="utf-8") as f:
        clip = json.load(f)

    controls, seen = [], set()
    for e in control:
        if e["dir"] != "pc_to_quest" or "capnp" not in e:
            continue
        key = (e["inner"]["type"], e["capnp"]["tree"]["s"][0] & 0xFFFF)
        if key in seen:
            continue
        seen.add(key)
        raw = bytes.fromhex(e["raw"])
        capnp = raw[16:16 + 8 + e["capnp"]["words"] * 8]
        controls.append((key[0], key[1], e["inner"]["flags"], capnp))

    slices = {}
    frame = clip["frame"]
    for i in range(1, len(frame)):
        prev, cur = bytes.fromhex(frame[i - 1]["body"]), frame[i]
        if len(prev) == 8 and frame[i - 1]["topic"] == cur["topic"]:
            slices[cur["topic"]] = (prev, bytes.fromhex(cur["body"]))

    out = ["// Generated by tools/gen_native_templates.py from the recorded handshake. Do not edit.",
           '#include "templates.hpp"', "", "namespace ql::templates {", "", "namespace {"]
    for n, (_, _, _, capnp) in enumerate(controls):
        out += [f"const uint8_t kControl{n}[] = {{", c_bytes(capnp), "};"]
    for n, m in enumerate(clip["setup"]):
        out += [f"const uint8_t kSetup{n}[] = {{", c_bytes(bytes.fromhex(m["body"])), "};"]
    for topic, (table, header) in sorted(slices.items()):
        out += [f"const uint8_t kSliceTable{topic}[] = {{", c_bytes(table), "};",
                f"const uint8_t kSliceHeader{topic}[] = {{", c_bytes(header), "};"]
    out += ["}  // namespace", ""]

    out.append("const std::vector<Control>& controls() {")
    out.append("    static const std::vector<Control> v = {")
    for n, (typ, ver, flags, capnp) in enumerate(controls):
        out.append(f"        {{0x{typ:02x}, {ver}, 0x{flags:02x}, {{kControl{n}, sizeof(kControl{n})}}}},")
    out += ["    };", "    return v;", "}", ""]

    out.append("const std::vector<SetupMessage>& stream_setup() {")
    out.append("    static const std::vector<SetupMessage> v = {")
    for n, m in enumerate(clip["setup"]):
        out.append(f"        {{{round(m['t'] * 1e9)}, {m['topic']}, 0x{m['flags']:02x}, {{kSetup{n}, sizeof(kSetup{n})}}}},")
    out += ["    };", "    return v;", "}", ""]

    out.append("const std::vector<SliceTemplate>& slice_headers() {")
    out.append("    static const std::vector<SliceTemplate> v = {")
    for topic in sorted(slices):
        out.append(f"        {{{topic}, {{kSliceTable{topic}, sizeof(kSliceTable{topic})}}, "
                   f"{{kSliceHeader{topic}, sizeof(kSliceHeader{topic})}}}},")
    out += ["    };", "    return v;", "}", "", "}  // namespace ql::templates", ""]

    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(out))
    print(f"{len(controls)} control, {len(clip['setup'])} setup, {len(slices)} slice templates -> "
          f"{os.path.relpath(OUT, ROOT)}")


if __name__ == "__main__":
    main()
